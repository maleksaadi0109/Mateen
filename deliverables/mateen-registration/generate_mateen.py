def card(s, x, y, w, h, label, body, marker=None):
    box(s, x, y, w, h)
    yy = y + .2
    if marker:
        text(s, marker, x+.2, yy, w-.4, .64, 30, "label", "secondary", True)
        yy += .78
    compact = h < 2
    gap = .45 if compact else .73
    text(s, label, x+.2, yy, w-.4, .6, 16 if marker or compact else 18,
         "label", "primary", True)
    text(s, body, x+.2, yy+gap, w-.4, h-(yy-y)-gap-.1, 18 if compact else 20)


def strip(s, value):
    text(s, value, .7, 6.22, 11.93, .59, 17, "body", "tertiary")


def notes(s, value):
    s.notes_slide.notes_text_frame.text = value


