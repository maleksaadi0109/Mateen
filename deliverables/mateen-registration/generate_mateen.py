from pptx.util import Inches, Pt

COLORS = {
    "primary": "6D4C3D", "secondary": "994703", "tertiary": "4E3A00",
    "paper": "FDF9F3", "text": "2A1F1A", "card": "F4EDE2",
}
FONTS = {"title": "Kufam", "label": "Cairo", "body": "Noto Naskh Arabic"}
W, H = 13.333333, 7.5


def color(name):
    return RGBColor.from_string(COLORS.get(name, name))


def box(slide, x, y, w, h, fill="card", border="primary", rounded=True):
    shape = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE if rounded else MSO_SHAPE.RECTANGLE,
        Inches(x), Inches(y), Inches(w), Inches(h),
    )
    shape.fill.solid()
    shape.fill.fore_color.rgb = color(fill)
    shape.line.color.rgb = color(border)
    shape.line.width = Pt(0.5)
    if rounded:
        shape.adjustments[0] = 0.10
    return shape


def text(slide, value, x, y, w, h, size=22, font="body",
         ink="text", bold=False, rtl=True):
    shape = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = shape.text_frame
    tf.clear()
    tf.word_wrap = True
    tf.margin_left = tf.margin_right = Inches(0.025)
    tf.margin_top = tf.margin_bottom = Inches(0.025)
    tf.vertical_anchor = MSO_ANCHOR.TOP
    for i, line in enumerate(value.split("\n")):
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.alignment = PP_ALIGN.RIGHT if rtl else PP_ALIGN.LEFT
        p.space_after = Pt(7)
        p.line_spacing = 1.12
        p._p.get_or_add_pPr().set("rtl", "1" if rtl else "0")
        run = p.add_run()
        run.text = line
        run.font.name = FONTS[font]
        run.font.size = Pt(size)
        run.font.bold = bold
        run.font.color.rgb = color(ink)
        rp = run._r.get_or_add_rPr()
        rp.set("lang", "ar-SA" if rtl else "en-US")
        # Complex-script typeface is essential for Arabic PowerPoint rendering.
        for tag in ("a:cs", "a:ea"):
            element = OxmlElement(tag)
            element.set("typeface", FONTS[font])
            rp.append(element)
    return shape


